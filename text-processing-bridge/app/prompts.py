from __future__ import annotations

from dataclasses import dataclass

# 議事録パイプラインが使う生成モデル。Ollamaへ渡すモデル名
DEFAULT_MODEL = "gemma4:26b"


@dataclass(frozen=True)
class PromptSpec:
    """1操作ぶんのプロンプトと生成条件。"""

    template: str
    num_predict: int
    temperature: float


SUMMARIZE = PromptSpec(
    template="""/no_think
あなたは日本語文章の厳密な要約器です。
出力は要約本文だけにし、説明、前置き、見出し、Markdownコードブロックを付けません。
原文にない情報を追加しません。
人名、数値、日付、決定事項、否定表現を保持します。
単なる抜き書きやフィラー除去で終わらせず、要点を整理して統合します。
同じ意味の文や隣接する重複文は一度だけ記載します。
要点ではない挨拶、進行上の定型句、言いよどみは省きます。
対象や目的語がなく具体的情報を持たない「確認します」「対応します」「お願いします」などの単独文は要点から省きます。
文字数上限が指定された場合のみ、必ず上限以内を目標にします。
上限の指定がない場合は、文字数を切り詰めすぎません。原文の3割から5割程度の分量を目安とし、
話題や項目が複数あるときは、それぞれを落とさず記載します。無理に一文へまとめません。
上限の有無にかかわらず、数値、固有名詞、担当者、期限、決定事項は省略しません。
再実行指示がある場合は、その指示も厳守します。

文字数上限：{max_chars}（0のときは上限なしとして扱い、文字数を制限しません）
再実行指示：{retry_instruction}

原文：
{text}
""",
    num_predict=6144,
    temperature=0.1,
)

REWRITE = PromptSpec(
    template="""/no_think
あなたは日本語文章の厳密な整形器です。
内容を変えず、文章を読みやすく整えてください。
情報の追加、要約、推測、意味変更は禁止です。
言いよどみやフィラーは除去し、同じ意味の隣接する重複文は一度だけ記載します。
再実行指示がある場合は、その指示も厳守します。
出力は整形後の本文だけにし、説明、前置き、Markdownコードブロックを付けません。

再実行指示：{retry_instruction}

原文：
{text}
""",
    num_predict=8192,
    temperature=0.1,
)

MINUTES = PromptSpec(
    template="""/no_think
あなたは日本語会議記録の厳密な整理器です。
原文にある情報だけを使います。
再実行指示で出力形式が指定された場合は、その形式に完全に従います。
形式の指定が無い場合だけ、次の固定形式で出力します。
概要：
決定事項：
対応事項：
原文に存在しない担当者や期限を補完しません。
該当情報がない項目は「記載なし」とします。
出力は議事録本文だけにし、説明、前置き、Markdownコードブロックを付けません。
文字数上限が指定された場合のみ上限以内を目標にします。
上限の指定がない場合は文字数を切り詰めすぎません。
原文に出てくる数値、金額、件数、日付、期限、担当者は、決定事項・対応事項の中に必ず含めます。
議題や論点が複数ある場合は、まとめずにそれぞれ項目として記載します。
再実行指示がある場合は厳守します。

文字数上限：{max_chars}（0のときは上限なしとして扱い、文字数を制限しません）
再実行指示：{retry_instruction}

会議内容：
{text}
""",
    num_predict=6144,
    temperature=0.0,
)

REFINE = PromptSpec(
    template="""/no_think
あなたは日本語文章の厳密な修正担当です。
与えられた文章へ修正指示だけを反映してください。
指示にない情報の追加、事実の変更、推測は禁止です。
出力は修正後の本文だけにし、説明、前置き、Markdownコードブロックを付けません。

修正指示：
{retry_instruction}

修正対象：
{text}
""",
    num_predict=8192,
    temperature=0.1,
)

# ケバ取り強で「削ってよい語」をLLMに挙げさせる。削除自体はコード側で行う
KEBATORI_DETECT = PromptSpec(
    template="""/no_think
あなたは日本語の会議文字起こしから、削除しても意味が変わらない短いつなぎ語だけを指摘する検出器です。
対象は、ひらがな・カタカナ中心の言いよどみやつなぎ語(まあ、なんか、こう、ですね、というか、うーん など)と無意味な間投詞だけです。
出力は削除してよい文字列のJSON配列だけとし、説明、前置き、Markdownコードブロックを付けません。
各要素は原文から一字一句そのまま引用し、12文字以内にします。
文全体や、漢字・数字を含む語句は絶対に挙げません。
「その資料」「あの件」のように意味を持つ語は挙げません。
返事としての「はい、わかりました」のような応答は挙げません。
文章の言い換えや要約は行いません。迷った場合は挙げません。
最大80件までとします。

原文:
{text}
""",
    num_predict=4096,
    temperature=0.1,
)

# LLMを使う操作と、そのプロンプト。ここに無い操作はコードだけで完結する
LLM_PROMPTS: dict[str, PromptSpec] = {
    "summarize": SUMMARIZE,
    "rewrite": REWRITE,
    "minutes": MINUTES,
    "refine": REFINE,
}
