"""
構造化議事録でLLMへ渡す指示文の生成。

次第から確定した項目一覧を提示し、LLMの仕事を「発言の振り分け」だけに
絞る。書式・文体・禁止事項はすべてここで指定する。
"""

from __future__ import annotations

from app.agenda_parse import Agenda, _item_key

# 完成した議事録から抜いた実例。抽象的な指示では報告と質疑を区別できないため、
# 具体例で線引きを示す。
GOOD_EXAMPLES = (
    "現在進めている共用ベッドの差配についてはできる限り早くお願いしたい。"
    "予算に対して100％を少し超えているので、今のままだと10億のマイナスと考えていいのか。",
    "今年はそれでいいのだが、来年が持たないので、110％は必要と考える。",
    "「エンハーツ点滴静注用100mg」だけは包括同意書ではなく、"
    "特別な同意書を取らなければならないのか。",
    "すでに同意書を作成し、横断的に使用できるようアップロードしている。",
    "ニュースレターはどこに配布しているのか。",
    "各部門に配布している。",
    "診療科毎の応需率は出るのか。",
    "それは出ない。7番窓口からつないだ診療科がどこなのか記録は取っていない。",
)
BAD_EXAMPLES = (
    "5月1日から5月10日までの稼働率は79.1%と大きく落ち込む結果となった。",
    "医薬品の新規採用が13件、診療材料の新規採用が5件であり、いずれも承認されている。",
    "外来診療地域連携関係に関しては、新規外来患者数をふやすことで、約7000万円増加。",
    "救急における向上率の維持について、39名センターは99.1%で目標を達成している。",
    "ホスピタリティマインド向上研修を7月21日に予定しており、現在調整中である。",
    "黄色の網掛けしているところが2ヶ月の病床稼働率である。",
)


def build_format_instruction(
    agenda: Agenda,
    roster: list[str] | None = None,
    block_index: int = 0,
    block_total: int = 1,
    covered: list[str] | None = None,
    missing_keys: list[str] | None = None,
    already: list[str] | None = None,
) -> str:
    """次第の項目一覧を示し、発言の振り分けだけをLLMに行わせる指示を作る。"""
    first_label = next(
        (_item_key(t.number, i.branch) for t, i in agenda.flat_items()),
        "1-1",
    )
    lines = [
        "出力形式を厳密に指定します。概要・決定事項・対応事項の形式は使いません。",
        "抽出するのは質疑応答・意見のみです。",
        "報告者が資料の内容を説明している部分は議事録に載せないため、出力しません。",
        "「誰が何を報告したか」は別途こちらで記載するので、書く必要はありません。",
        "質問、意見、依頼、指摘、回答、確認事項だけを抜き出し、",
        "下記の項目一覧のどれかへ振り分けてください。",
        "",
        "【項目一覧】",
    ]
    for topic, item in agenda.flat_items():
        label = _item_key(topic.number, item.branch)
        detail = f"  {label} 議題{topic.number} {topic.title}"
        if item.title:
            detail += f" / {item.title}"
        if item.material:
            detail += f" / {item.material}"
        if item.owner:
            detail += f" / 担当予定: {item.owner_display()}"
        lines.append(detail)
    lines += [
        "",
        "【出力形式】各行を次のいずれかで始めます。他の文字は一切出力しません。",
        "##項目 <記号>",
        "##報告 <報告者名>",
        "##資料 <資料番号>",
        "##発言 <発言者名> | <発言内容>",
        "##報告内容 <報告の内容>",
        "",
        f"記号は上の一覧の先頭にある「{first_label}」の形だけを書きます。",
        "議題名や項目名を記号の後ろに書いてはいけません。記号に何も足しません。",
        f"正しい例: ##項目 {first_label}",
        f"誤った例: ##項目 {first_label} 議題の名前をここに書く",
        "",
        "規則:",
        "- 項目の行を書いてから、##報告 の行、続けてその項目に属する発言を並べます。",
        "- ##報告 には、その項目で実際に資料の説明を行った人の呼称を書きます。",
        "  「○○が資料Nに基づき説明します」と述べた人、または議長から指名されて",
        "  報告を始めた人です。発言内容は不要でも、この行は必ず判定してください。",
        "  会議内容から誰が説明したか読み取れない場合だけ、##報告 の行を省略します。",
        "- ##資料 には、その項目で実際に言及された資料番号(例: 資料1)を書きます。",
        "  会議内容に資料番号が出てこない場合は、##資料 の行を省略します。",
        "- ##報告 と ##資料 は推測で書いてはいけません。分からなければ省略します。",
        "- 発言内容に人名が出てくる場合だけ、下記の名簿と担当者名を正として",
        "  同じ漢字で書きます。読みが一致する人が一覧にいなければそのまま書きます。",
        "- 同じ内容の発言を繰り返し出力してはいけません。",
        "  一度書いた発言と同じ趣旨のものは、二度目以降は出力しません。",
        "- 音声認識の誤りで意味が通らない箇所は、その部分を出力しません。",
        "  文全体が意味不明な場合は、その発言ごと省きます。",
        "  推測で補って意味の通る文に仕立ててはいけません。",
        "- 発言者名は会議内容に出てくる呼称をそのまま使います。推測しません。",
        "- 報告者が資料を読み上げている部分は ##報告内容 の行にします。",
        "  質問・意見・依頼・指摘・回答は ##発言 の行にします。",
        "  どちらか迷った場合は ##発言 にしてください。",
        "  明らかに実績値や予定を読み上げているだけの部分だけを ##報告内容 にします。",
        "  質問への回答、意見、依頼、指摘は、数値を含んでいても ##発言 です。",
        "- 発言者名は、文字起こしから確実に分かる場合だけ書きます。",
        "  「○○先生お願いします」と指名された直後の発言、名乗った発言などです。",
        "  分からない場合は空にして「##発言  | 内容」と書きます。",
        "  「議長」「担当者」「医師」のような役割名で埋めることは禁止します。",
        "  推測で名前を書くくらいなら、必ず空にしてください。",
        "- 発言は1件ずつ、発言の区切りごとに分けて出力します。",
        "  議論全体を要約してはいけません。",
        "- 質問とその回答は、必ず両方をセットで、やり取りの順のまま出力します。",
        "  回答だけ、質問だけを落としてはいけません。",
        "  質問→回答→再質問→回答と続くやり取りは、往復をすべてその順で出力します。",
        "- 「承知した。」「各部門に配布している。」のような短い回答も、",
        "  直前の質問への答えなので必ず1件として出力します。",
        "- 発言内容は、話し言葉をそのまま写すのではなく、議事録の書き言葉へ直します。",
        "  文体は上の○の例と同じです。文末は「〜である」「〜と考える」「〜のか」",
        "  「〜してほしい」「〜する」のいずれかに整えます。",
        "  「〜でございました」「〜な気がしますけど」「〜いいんじゃないか」のような",
        "  話し言葉は「〜である」「〜と考える」「〜する方がよいのではないか」へ直します。",
        "  「ですね」「けども」「ちょっと」「あの」などの冗長語は取り除きます。",
        "- 整えるのは文体だけです。論点は1つも削りません。",
        "  数値、金額、件数、日付、期限、固有名詞、担当者名は必ず残します。",
        "  質問には質問の趣旨を、回答には回答の中身を、依頼には依頼の条件を残します。",
        "  1つの発言に複数の論点があれば、すべて書きます。",
        "- 報告者が資料を説明しているだけの発言は出力しません。",
        "  例:「資料1に基づきご説明します」「入院収益は102％となっております」は不要。",
        "  ただし、その説明に対する質問や意見への回答は出力します。",
        "- 該当する発言が無い項目は、##項目 の行も出力しません。",
        "- 項目一覧に無い記号は使いません。どれにも属さない発言は ##項目 その他 に入れます。",
    ]
    if block_total > 1:
        lines += [
            "",
            f"【この部分について】全{block_total}分割のうち{block_index + 1}番目です。",
            "会議は次第の順に進みます。ここは会議全体の"
            f"{int(block_index / block_total * 100)}%〜"
            f"{int((block_index + 1) / block_total * 100)}%あたりにあたります。",
            "この範囲で扱われている議題は限られます。一覧の全項目に",
            "振り分けようとせず、実際に話されている項目だけを出力してください。",
        ]
        if covered:
            lines.append(
                "直前までの部分で既に扱われた項目: " + "、".join(covered)
            )
            lines.append(
                "会議は前へ戻らないため、これらより後の項目が中心になります。"
            )

    lines += [
        "",
        "【出力する発言の例】質問・意見・依頼・指摘・それらへの回答",
    ]
    lines += [f"  ○ {text}" for text in GOOD_EXAMPLES]
    lines += [
        "",
        "【出力しない発言の例】報告者が資料の内容を読み上げている部分",
    ]
    lines += [f"  × {text}" for text in BAD_EXAMPLES]
    lines += [
        "",
        "×の例に共通するのは、実績値や予定を淡々と述べているだけで、",
        "誰かに問いかけたり、意見を述べたり、依頼したりしていない点です。",
        "数値や実績の報告は、それがどれだけ重要でも出力しません。",
        "質疑が交わされなかった項目は、##項目 の行ごと出力しません。",
        "0件で構いません。無理に埋めないでください。",
    ]

    if roster:
        lines += [
            "",
            "【出席者名簿】この表記を正として発言者名を書きます。",
            "  " + "、".join(roster),
            "  呼称も名簿を正とします。名簿に「乙野教授」とあれば",
            "  「乙野先生」ではなく「乙野教授」と書きます。",
        ]

    if missing_keys:
        lines += [
            "",
            "【注意】1回目の抽出では、次の項目に発言が見つかりませんでした:",
            "  " + "、".join(missing_keys),
            "この範囲に該当する発言があれば、特に注意して抽出してください。",
            "ただし、無いものを作ってはいけません。他の項目も通常どおり出力します。",
        ]

    if already:
        lines += [
            "",
            "【既出一覧】次の発言は1回目の抽出で既に拾われています。",
            "同じ発言はもちろん、同じ趣旨の言い換えも出力してはいけません。",
            "この一覧に無い発言だけを出力してください。無ければ何も出力しません。",
        ]
        lines += [f"  ・{text}" for text in already]
    return "\n".join(lines)


def build_topic_inference_instruction(
    block_index: int, block_total: int, known: list[str]
) -> str:
    """文字起こしから議題の区切りと表題を推定させる指示を作る。"""
    lines = [
        "出力形式を厳密に指定します。議事録は作りません。",
        "この文字起こしで扱われた議題(話題のまとまり)を、出てくる順に挙げてください。",
        "出力は次の形式の行だけです。他の文字は一切出力しません。",
        "#議題 <表題>",
        "",
        "規則:",
        "- 表題は6〜20字程度の名詞句にします。文や要約にはしません。",
        "  例: ○「病床稼働率の向上について」 ×「稼働率を上げるべきという議論があった」",
        "- 話題が変わったところで区切ります。細かく割りすぎません(この部分で1〜5個)。",
        "- 挨拶・雑談・日程調整だけの部分は議題にしません。",
        "- 文字起こしに出てこない話題を作ってはいけません。",
    ]
    if block_total > 1:
        lines += [
            "",
            f"これは全{block_total}分割のうち{block_index + 1}番目の部分です。",
        ]
    if known:
        lines += [
            "直前までに挙がった議題: " + "、".join(known),
            "同じ話題が続いているだけなら何も出力しません。新しい話題だけを挙げます。",
        ]
    return "\n".join(lines)
